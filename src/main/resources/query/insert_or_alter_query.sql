-- CREATE SEQUENCE FOR FD_COMPANY_APPROVER TABLE
CREATE SEQUENCE APPROVER_SEQ
    START WITH 1
    INCREMENT BY 1;

-- CREATE FD_COMPANY_APPROVER TABLE
CREATE TABLE FD_COMPANY_APPROVER
(
    APPROVER_ID BIGINT PRIMARY KEY DEFAULT nextval('APPROVER_SEQ'),
    COMPANY_ID BIGINT NOT NULL,
    AGENT_ID BIGINT NOT NULL,
    LEVEL INT NOT NULL,
    IS_ACTIVE         BOOLEAN            DEFAULT TRUE,
    CREATED_BY        BIGINT       NOT NULL,
    UPDATED_BY        BIGINT,
    IS_CREATOR_ADMIN  BOOLEAN      NOT NULL,
    IS_UPDATER_ADMIN  BOOLEAN            DEFAULT FALSE,
    CREATED_AT        TIMESTAMP          DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT        TIMESTAMP          DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_COMPANY_APPROVER_COMPANY FOREIGN KEY (COMPANY_ID)
        REFERENCES FD_COMPANY_MASTER (COMPANY_ID),
    CONSTRAINT FK_COMPANY_APPROVER_AGENT FOREIGN KEY (AGENT_ID)
        REFERENCES FD_AGENT_MASTER (AGENT_ID)
);