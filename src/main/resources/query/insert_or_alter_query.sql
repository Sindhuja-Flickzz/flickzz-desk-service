-- To update description for fd_approval_master table for existing records
UPDATE fd_approval_master a
SET    description = CASE
                         WHEN a.request_type = 'BP' THEN
                             Concat(c.remark_type, ' - ',
                                    COALESCE(c.remark, ''))
                         WHEN a.request_type = 'RITM' THEN
                             Concat('Approval for RITM ', rm.ritm_number)
                         ELSE a.description
    END
    FROM   fd_config_change_request_remark c,
       fd_ritm_approver ra
       INNER JOIN fd_ritm_master rm
ON rm.ritm_id = ra.ritm_id
WHERE  ( a.request_type = 'BP'
  AND c.ccr_id = a.request_id )
   OR ( a.request_type = 'RITM'
  AND ra.ritm_approver_id = a.request_id );

