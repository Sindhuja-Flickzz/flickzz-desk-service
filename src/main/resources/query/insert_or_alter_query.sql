CREATE SEQUENCE FD_CHANGE_REQUEST_SEQ
    START WITH 1
    INCREMENT BY 1;

-- FD_CONFIG_CHANGE_REQUEST TABLE
CREATE TABLE FD_CONFIG_CHANGE_REQUEST
(
    CCR_ID                          BIGINT PRIMARY KEY DEFAULT NEXTVAL('FD_CHANGE_REQUEST_SEQ'),
    CONFIGURATION_ID                BIGINT NOT NULL,
    CHANGED_REQUEST_ID				BIGINT NOT NULL,
    SOURCE_CHANGE_ID 				BIGINT,
    IS_BP_PRIORITY 					BOOLEAN DEFAULT FALSE,
    IS_BP_SLA 						BOOLEAN DEFAULT FALSE,
    IS_CATEGORY 					BOOLEAN DEFAULT FALSE,
    IS_SUPPORT_GROUP 				BOOLEAN DEFAULT FALSE,
    IS_ASSIGNMENT 					BOOLEAN DEFAULT FALSE,
    OPERATION                       VARCHAR(20) NOT NULL,
    REQUESTED_BY_ORG             	BIGINT NOT NULL,
    REQUESTED_BY_USER_ID            BIGINT NOT NULL,
    APPROVAL_ORG                    BIGINT NOT NULL,
    STATUS                          VARCHAR(30) NOT NULL,
    TOTAL_INTERNAL_APPROVAL_LEVELS  INT NOT NULL,
    TOTAL_BP_APPROVAL_LEVELS        INT NOT NULL,
    CURRENT_INTERNAL_APPROVAL_LEVEL INT DEFAULT 0,
    CURRENT_BP_APPROVAL_LEVEL       INT DEFAULT 0,
    REQUESTED_ON                    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    COMPLETED_ON                    TIMESTAMP NULL,
    CREATED_BY                      BIGINT NOT NULL,
    CREATED_ON                      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY                      BIGINT,
    UPDATED_ON                      TIMESTAMP,
    IS_CREATOR_ADMIN    			BOOLEAN,

    CONSTRAINT FK_CCR_TARGET_CONFIG
        FOREIGN KEY (CONFIGURATION_ID)
            REFERENCES FD_BP_CONFIGURATION(CONFIGURATION_ID),

    CONSTRAINT FK_CCR_REQUESTED_BY_ORG
        FOREIGN KEY (REQUESTED_BY_ORG)
            REFERENCES FD_COMPANY_MASTER(COMPANY_ID),

    CONSTRAINT FK_CCR_APPROVAL_ORG
        FOREIGN KEY (APPROVAL_ORG_ID)
            REFERENCES FD_COMPANY_MASTER(COMPANY_ID)
);

