-- CREATE SEQUENCE FOR FD_PLANT_WEEKOFF TABLE
CREATE SEQUENCE WEEKOFF_SEQ
    START WITH 1
    INCREMENT BY 1;

-- CREATE FD_PLANT_WEEKOFF TABLE
CREATE TABLE FD_PLANT_WEEKOFF
(
    WEEKOFF_ID       BIGINT PRIMARY KEY DEFAULT nextval('WEEKOFF_SEQ'),
    WEEKOFF          VARCHAR(20) NOT NULL, -- e.g., "Monday", "Tuesday"
    PLANT_ID         BIGINT      NOT NULL, -- FK to FD_PLANT_MASTER
    IS_ACTIVE        BOOLEAN            DEFAULT TRUE,
    CREATED_BY       BIGINT      NOT NULL,
    UPDATED_BY       BIGINT,
    IS_CREATOR_ADMIN BOOLEAN     NOT NULL,
    IS_UPDATER_ADMIN BOOLEAN            DEFAULT FALSE,
    CREATED_AT       TIMESTAMP          DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT       TIMESTAMP          DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_WEEKOFF_PLANT FOREIGN KEY (PLANT_ID)
        REFERENCES FD_PLANT_MASTER (PLANT_ID)
);